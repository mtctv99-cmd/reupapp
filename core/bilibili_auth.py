"""Bilibili QR login + cookie management."""
import json
import logging
import ssl
import time
import urllib.parse
import urllib.request
from pathlib import Path

logger = logging.getLogger(__name__)

_API_CTX = ssl.create_default_context()

_HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/131.0.0.0 Safari/537.36",
    "Referer": "https://www.bilibili.com",
}


def generate_qrcode() -> dict:
    """Generate Bilibili QR code for login. Returns {url, qrcode_key}."""
    req = urllib.request.Request(
        "https://passport.bilibili.com/x/passport-login/web/qrcode/generate",
        headers=_HEADERS,
    )
    with urllib.request.urlopen(req, context=_API_CTX, timeout=10) as resp:
        data = json.loads(resp.read().decode())
    if data.get("code") != 0:
        raise RuntimeError(f"QR generate failed: {data}")
    d = data["data"]
    return {"url": d["url"], "qrcode_key": d["qrcode_key"]}


def poll_qrcode(qrcode_key: str) -> dict:
    """Poll QR code scan status. Returns {status, cookies?, message?}.

    status: "scan_success" | "expired" | "waiting"
    """
    params = urllib.parse.urlencode({"qrcode_key": qrcode_key})
    req = urllib.request.Request(
        f"https://passport.bilibili.com/x/passport-login/web/qrcode/poll?{params}",
        headers=_HEADERS,
    )
    with urllib.request.urlopen(req, context=_API_CTX, timeout=10) as resp:
        data = json.loads(resp.read().decode())

    if data.get("code") != 0:
        return {"status": "error", "message": data.get("message", "unknown")}

    d = data["data"]
    code = d.get("code", 0)

    # 0=success, 86038=expired, 86090=scanned wait confirm, 86101=not scanned
    if code == 0:
        # Login success — extract cookies from URL
        url = d.get("url", "")
        return {"status": "scan_success", "url": url, "message": "Đăng nhập thành công!"}
    elif code == 86038:
        return {"status": "expired", "message": "QR code đã hết hạn"}
    else:
        return {"status": "waiting", "message": "Đang chờ quét..."}


def parse_cookies_from_url(url: str) -> str:
    """Parse cookie string from Bilibili login redirect URL."""
    if not url:
        return ""
    # URL typically contains ?DedeUserID=xx&SESSDATA=xx&bili_jct=xx
    parsed = urllib.parse.urlparse(url)
    params = urllib.parse.parse_qs(parsed.query)
    cookies = []
    for key in ("DedeUserID", "DedeUserID__ckMd5", "SESSDATA", "bili_jct", "buvid3", "b_nut"):
        vals = params.get(key, [])
        if vals:
            cookies.append(f"{key}={vals[0]}")
    return "; ".join(cookies)


def check_login_status(cookie_str: str) -> dict:
    """Check if Bilibili cookie is valid. Returns {logged_in, username?, message?}."""
    if not cookie_str:
        return {"logged_in": False, "message": "Chưa có cookie"}

    headers = {**_HEADERS, "Cookie": cookie_str}
    try:
        req = urllib.request.Request(
            "https://api.bilibili.com/x/web-interface/nav",
            headers=headers,
        )
        with urllib.request.urlopen(req, context=_API_CTX, timeout=10) as resp:
            data = json.loads(resp.read().decode())

        if data.get("code") == 0 and data.get("data", {}).get("isLogin"):
            uname = data["data"].get("uname", "")
            return {"logged_in": True, "username": uname, "message": f"Đã đăng nhập: {uname}"}
        return {"logged_in": False, "message": "Cookie không hợp lệ hoặc đã hết hạn"}
    except Exception as exc:
        return {"logged_in": False, "message": f"Lỗi kiểm tra: {exc}"}


def save_cookie(cookie_str: str, cookie_dir: str) -> str:
    """Save cookie to file, return file path."""
    Path(cookie_dir).mkdir(parents=True, exist_ok=True)
    path = Path(cookie_dir) / "bilibili_cookies.txt"
    # Convert "; " format to Netscape cookie format for yt-dlp/BBDown
    lines = ["# Netscape HTTP Cookie File", "# This file is generated by Sever Dub Studio Pro", ""]
    for pair in cookie_str.split("; "):
        if "=" in pair:
            name, value = pair.split("=", 1)
            lines.append(f".bilibili.com\tTRUE\t/\tFALSE\t0\t{name}\t{value}")
    path.write_text("\n".join(lines), encoding="utf-8")
    return str(path)


def load_cookie(cookie_dir: str) -> str:
    """Load cookie from file."""
    path = Path(cookie_dir) / "bilibili_cookies.txt"
    if not path.exists():
        return ""
    lines = path.read_text("utf-8").splitlines()
    cookies = []
    for line in lines:
        line = line.strip()
        if line.startswith("#") or not line or "\t" not in line:
            continue
        parts = line.split("\t")
        if len(parts) >= 7:
            cookies.append(f"{parts[5]}={parts[6]}")
    return "; ".join(cookies)
